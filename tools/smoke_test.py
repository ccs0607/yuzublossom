from playwright.sync_api import sync_playwright, expect
from pathlib import Path
import json, os
from PIL import Image
OUT = Path('output/qa')
OUT.mkdir(parents=True, exist_ok=True)
EXE = os.environ.get('BROWSER_PATH', r'C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe')
URL = os.environ.get('TEST_URL', 'http://127.0.0.1:8000/')
checks, errors, network = [], [], []
def ok(name): checks.append(name)
def watch(page):
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.on('response', lambda response: network.append({'url':response.url,'status':response.status}) if response.status >= 400 else None)
def moon_location(page):
    return page.evaluate('''() => {
      const img=document.querySelector('#sceneImage'), b=img.getBoundingClientRect(), h=document.querySelector('#home').getBoundingClientRect();
      const s=Math.max(b.width/img.naturalWidth,b.height/img.naturalHeight);
      const pos=getComputedStyle(img).objectPosition.split(' ').map(n=>parseFloat(n)/100);
      return {x:b.left-h.left+(b.width-img.naturalWidth*s)*pos[0]+img.naturalWidth*s*.665,y:b.top-h.top+(b.height-img.naturalHeight*s)*pos[1]+img.naturalHeight*s*.255};
    }''')
