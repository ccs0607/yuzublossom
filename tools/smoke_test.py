    actual=page.locator('.moon-ring').evaluate('e=>({x:parseFloat(e.style.left),y:parseFloat(e.style.top)})')
    expected=moon_location(page)
    assert abs(actual['x']-expected['x'])<5 and abs(actual['y']-expected['y'])<5, (actual,expected)
    ok('Moon ripple matches the rendered image coordinates')
    page.locator('[data-mood=osmanthus]').click()
